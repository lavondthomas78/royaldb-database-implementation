DROP TABLE IF EXISTS customer;

CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(120) NOT NULL,
    contact_first_name VARCHAR(60) NOT NULL,
    contact_last_name VARCHAR(60) NOT NULL,
    contact_email VARCHAR(120) NOT NULL,
    contact_phone VARCHAR(25),
    customer_status VARCHAR(20) NOT NULL
        CHECK (customer_status IN ('Active','Inactive')),
    created_date DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE location (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer(customer_id),
    location_name VARCHAR(100) NOT NULL,
    address_line1 VARCHAR(120) NOT NULL,
    address_line2 VARCHAR(120),
    city VARCHAR(60) NOT NULL,
    state VARCHAR(30) NOT NULL,
    postal_code VARCHAR(15) NOT NULL,
    location_phone VARCHAR(25),
    location_status VARCHAR(20) NOT NULL
        CHECK (location_status IN ('Active','Inactive'))
);

CREATE TABLE device (
    device_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id INTEGER NOT NULL REFERENCES location(location_id),
    device_name VARCHAR(100) NOT NULL,
    device_type VARCHAR(40) NOT NULL,
    manufacturer VARCHAR(60),
    model VARCHAR(60),
    serial_number VARCHAR(80),
    ip_address VARCHAR(45),
    operating_system VARCHAR(100),
    purchase_date DATE,
    warranty_expiration DATE,
    device_status VARCHAR(20) NOT NULL
        CHECK (device_status IN ('Active','Inactive','Maintenance','Retired'))
);

CREATE TABLE contract (
    contract_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer(customer_id),
    contract_type VARCHAR(60) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    service_level VARCHAR(20) NOT NULL
        CHECK (service_level IN ('Standard','Priority','Premium')),
    contract_status VARCHAR(20) NOT NULL
        CHECK (contract_status IN ('Active','Pending','Expired','Terminated')),
    monthly_rate NUMERIC(10,2) NOT NULL CHECK (monthly_rate >= 0),
    CHECK (end_date >= start_date)
);

CREATE TABLE technician (
    technician_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    phone VARCHAR(25),
    job_title VARCHAR(80) NOT NULL,
    skill_level VARCHAR(20) NOT NULL
        CHECK (skill_level IN ('Level 1','Level 2','Level 3','Specialist')),
    technician_status VARCHAR(20) NOT NULL
        CHECK (technician_status IN ('Active','Inactive','Leave'))
);

CREATE TABLE ticket (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer(customer_id),
    device_id INTEGER REFERENCES device(device_id),
    ticket_title VARCHAR(150) NOT NULL,
    ticket_description TEXT NOT NULL,
    priority VARCHAR(20) NOT NULL
        CHECK (priority IN ('Low','Medium','High','Critical')),
    ticket_status VARCHAR(20) NOT NULL
        CHECK (ticket_status IN ('New','Open','In Progress','Pending','Resolved','Closed')),
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_date TIMESTAMP,
    closed_date TIMESTAMP,
    CHECK (resolved_date IS NULL OR resolved_date >= created_date),
    CHECK (closed_date IS NULL OR closed_date >= created_date)
);

CREATE TABLE ticket_assignment (
    assignment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES ticket(ticket_id),
    technician_id INTEGER NOT NULL REFERENCES technician(technician_id),
    assigned_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assignment_role VARCHAR(60) NOT NULL,
    hours_worked NUMERIC(6,2) CHECK (hours_worked IS NULL OR hours_worked >= 0),
    assignment_status VARCHAR(20) NOT NULL
        CHECK (assignment_status IN ('Assigned','In Progress','Completed','Escalated'))
);

