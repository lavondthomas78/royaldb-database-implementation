-- 1. SELECT / FROM: list active customers
SELECT customer_id, company_name, contact_email
FROM customer
WHERE customer_status = 'Active';

-- 2. WHERE: high-priority and critical tickets
SELECT ticket_id, ticket_title, priority, ticket_status
FROM ticket
WHERE priority IN ('High','Critical');

-- 3. BETWEEN: contracts starting during calendar year 2026
SELECT contract_id, customer_id, start_date, end_date, service_level
FROM contract
WHERE start_date BETWEEN '2026-01-01' AND '2026-12-31';

-- 4. IN: tickets in active workflow states
SELECT ticket_id, ticket_title, ticket_status
FROM ticket
WHERE ticket_status IN ('New','Open','In Progress','Pending');

-- 5. LIKE: locate devices whose names begin with NS-
SELECT device_id, device_name, device_type
FROM device
WHERE device_name LIKE 'NS-%';

-- 6. IS NULL: tickets that are not tied to a physical device
SELECT ticket_id, customer_id, ticket_title
FROM ticket
WHERE device_id IS NULL;

-- 7. JOIN: show tickets with customer names
SELECT t.ticket_id,
       c.company_name,
       t.ticket_title,
       t.priority,
       t.ticket_status
FROM ticket t
JOIN customer c ON c.customer_id = t.customer_id
ORDER BY t.ticket_id;

-- 8. Multi-table JOIN: show technician assignments
SELECT ta.assignment_id,
       t.ticket_id,
       t.ticket_title,
       tech.first_name,
       tech.last_name,
       ta.assignment_role,
       ta.assignment_status
FROM ticket_assignment ta
JOIN ticket t ON t.ticket_id = ta.ticket_id
JOIN technician tech ON tech.technician_id = ta.technician_id
ORDER BY ta.assignment_id;

-- 9. Subquery: tickets for customers with active service contracts
SELECT ticket_id, customer_id, ticket_title, ticket_status
FROM ticket
WHERE customer_id IN (
    SELECT customer_id
    FROM contract
    WHERE contract_status = 'Active'
);

