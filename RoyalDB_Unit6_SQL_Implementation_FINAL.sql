-- 19. Create non-login group roles only if they do not already exist.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'royaldb_dba') THEN
        CREATE ROLE royaldb_dba NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'royaldb_tech') THEN
        CREATE ROLE royaldb_tech NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'royaldb_readonly') THEN
        CREATE ROLE royaldb_readonly NOLOGIN;
    END IF;
END
$$;

-- 20. Database and schema access.
GRANT CONNECT ON DATABASE royaldb
TO royaldb_dba, royaldb_tech, royaldb_readonly;

GRANT USAGE ON SCHEMA public
TO royaldb_dba, royaldb_tech, royaldb_readonly;

-- 21. DBA privileges.
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public
TO royaldb_dba;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public
TO royaldb_dba;

-- 22. Technician privileges.
GRANT SELECT ON ALL TABLES IN SCHEMA public
TO royaldb_tech;
GRANT INSERT, UPDATE ON ticket, ticket_assignment
TO royaldb_tech;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public
TO royaldb_tech;

-- 23. Read-only privileges.
