-- 15. Corrected Customer-Ticket-Device JOIN.
-- The physical PostgreSQL schema uses snake_case identifiers
-- (customer_id, ticket_id, device_id), not conceptual CamelCase names.
SELECT
    t.ticket_id,
    c.company_name,
    t.ticket_title,
    t.priority,
    t.ticket_status,
    d.device_name
FROM ticket AS t
JOIN customer AS c
    ON t.customer_id = c.customer_id
LEFT JOIN device AS d
    ON t.device_id = d.device_id
ORDER BY t.ticket_id;

